API_URL = "http://localhost:8000/analyze"

def run_batch_tests():
    print("=" * 80)
    print("🚀 Запуск пакетного анализа 10 exit-интервью через HR Exit Engine")
    print("=" * 80)

    results = []
    total_start_time = time.time()

    for item in CASES:
        case_id = item["id"]
        title = item["title"]
        text = item["text"]

        print(f"\n[{case_id}/10] Обработка кейса: «{title}»...")
        start_t = time.time()

        try:
            resp = requests.post(API_URL, json={"text": text}, timeout=60)
            elapsed = time.time() - start_t

            if resp.status_code == 200:
                data = resp.json()
                results.append({
                    "id": case_id,
                    "title": title,
                    "status": "OK",
                    "time": elapsed,
                    "risk": data.get("risk_zone", "N/A"),
                    "reason": data.get("exit_reason", "N/A"),
                    "pains_cnt": len(data.get("pain_points", [])),
                    "best_cnt": len(data.get("best_practices", [])),
                    "first_rec": data.get("improvement_suggestions", ["Нет"])[0]
                })
                print(f"   ✅ Успешно за {elapsed:.2f} сек. Риск: {data.get('risk_zone')} | Причина: {data.get('exit_reason')}")
            else:
                results.append({
                    "id": case_id,
                    "title": title,
                    "status": f"HTTP {resp.status_code}",
                    "time": elapsed,
                    "risk": "-",
                    "reason": resp.text[:40],
                    "pains_cnt": 0,
                    "best_cnt": 0,
                    "first_rec": "-"
                })
                print(f"   ❌ Ошибка {resp.status_code}: {resp.text}")

        except Exception as ex:
            elapsed = time.time() - start_t
            results.append({
                "id": case_id,
                "title": title,
                "status": "EXC",
                "time": elapsed,
                "risk": "-",
                "reason": str(ex)[:40],
                "pains_cnt": 0,
                "best_cnt": 0,
                "first_rec": "-"
            })
            print(f"   ❌ Исключение: {ex}")

        # Небольшая пауза между вызовами YandexGPT
        time.sleep(1)

    total_time = time.time() - total_start_time

    # Вывод итоговой сводки
    print("\n" + "=" * 95)
    print("📊 СВОДНЫЙ ПАСПОРТ ОБРАБОТАННЫХ ИНТЕРВЬЮ")
    print("=" * 95)
    header = f"{'ID':<3} | {'Статус':<6} | {'Время':<6} | {'Риск':<6} | {'Боли/Плюс':<9} | {'Причина ухода'}"
    print(header)
    print("-" * 95)

    for r in results:
        status_icon = "🟢" if r["status"] == "OK" else "🔴"
        stats = f"{r['pains_cnt']}/{r['best_cnt']}"
        time_str = f"{r['time']:.1f}с"
        print(f"{r['id']:<3} | {status_icon} {r['status']:<4} | {time_str:<6} | {r['risk']:<6} | {stats:<9} | {r['reason']}")

    print("-" * 95)
    success_count = sum(1 for r in results if r["status"] == "OK")
    print(f"Всего кейсов: {len(CASES)} | Успешно: {success_count}/{len(CASES)} | Общее время: {total_time:.1f} сек")
    print("=" * 95)

if __name__ == "__main__":
    run_batch_tests()